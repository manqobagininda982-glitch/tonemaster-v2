-- Profiles (one per account, created automatically on signup)
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '',
  display_name text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
grant select, update on public.profiles to authenticated;
grant all on public.profiles to service_role;
alter table public.profiles enable row level security;
create policy "Users read own profile" on public.profiles for select to authenticated using (auth.uid() = id);
create policy "Users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "Admins read all profiles" on public.profiles for select to authenticated using (public.has_role(auth.uid(),'admin'));

create or replace function public.profiles_guard() returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  if coalesce(auth.role(), '') <> 'service_role' and current_user <> 'postgres' then
    new.email := old.email; new.id := old.id; new.created_at := old.created_at;
  end if;
  new.display_name := left(trim(new.display_name), 80);
  return new;
end $$;
create trigger profiles_guard before update on public.profiles for each row execute function public.profiles_guard();

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, display_name)
  values (new.id, coalesce(new.email, ''), left(coalesce(new.raw_user_meta_data->>'display_name', split_part(coalesce(new.email,''), '@', 1)), 80))
  on conflict (id) do nothing;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

-- Per-account app settings (synced from the Main App)
create table public.user_settings (
  user_id uuid primary key,
  settings jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
grant select, insert, update on public.user_settings to authenticated;
grant all on public.user_settings to service_role;
alter table public.user_settings enable row level security;
create policy "Users read own settings" on public.user_settings for select to authenticated using (auth.uid() = user_id);
create policy "Users insert own settings" on public.user_settings for insert to authenticated with check (auth.uid() = user_id and octet_length(settings::text) < 20000);
create policy "Users update own settings" on public.user_settings for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id and octet_length(settings::text) < 20000);
create policy "Admins read settings" on public.user_settings for select to authenticated using (public.has_role(auth.uid(),'admin'));

-- Licence keys (generated by administrators, bound to one account + one phone on activation)
create table public.licences (
  id uuid primary key default gen_random_uuid(),
  licence_key text not null unique,
  status text not null default 'available' check (status in ('available','active','revoked')),
  price_zar numeric(10,2) not null default 250,
  customer_name text not null default '',
  customer_email text not null default '',
  notes text not null default '',
  user_id uuid,
  device_id text,
  activated_at timestamptz,
  last_validated_at timestamptz,
  revoked_at timestamptz,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index licences_user_idx on public.licences(user_id);
grant select, update, delete on public.licences to authenticated;
grant all on public.licences to service_role;
alter table public.licences enable row level security;
create policy "Users read own licences" on public.licences for select to authenticated using (auth.uid() = user_id);
create policy "Admins read licences" on public.licences for select to authenticated using (public.has_role(auth.uid(),'admin'));
create policy "Admins update licences" on public.licences for update to authenticated using (public.has_role(auth.uid(),'admin')) with check (public.has_role(auth.uid(),'admin'));
create policy "Admins delete licences" on public.licences for delete to authenticated using (public.has_role(auth.uid(),'admin'));

create or replace function public.licences_guard() returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  new.licence_key := old.licence_key;
  if new.status = 'revoked' and old.status <> 'revoked' then new.revoked_at := now(); end if;
  if new.status <> 'revoked' then new.revoked_at := null; end if;
  if new.user_id is null then new.device_id := null; new.activated_at := null; if new.status = 'active' then new.status := 'available'; end if; end if;
  return new;
end $$;
create trigger licences_guard before update on public.licences for each row execute function public.licences_guard();

-- Admin: generate licence keys like TMK-ABCDE-FGHJK-MNPQR-STVWX (100 random bits)
create or replace function public.admin_generate_licences(_count integer, _customer_name text default '', _customer_email text default '', _notes text default '')
returns setof public.licences language plpgsql security definer set search_path = public as $$
declare
  alphabet constant text := '23456789ABCDEFGHJKMNPQRSTUVWXYZ';
  b bytea; k text; i integer; n integer;
begin
  if not public.has_role(auth.uid(), 'admin') then raise exception 'Administrator access required'; end if;
  if _count is null or _count < 1 or _count > 200 then raise exception 'Generate between 1 and 200 keys at a time'; end if;
  for n in 1.._count loop
    loop
      b := uuid_send(gen_random_uuid()) || uuid_send(gen_random_uuid());
      k := 'TMK';
      for i in 0..19 loop
        if i % 5 = 0 then k := k || '-'; end if;
        k := k || substr(alphabet, (get_byte(b, i) % 31) + 1, 1);
      end loop;
      exit when not exists (select 1 from public.licences where licence_key = k);
    end loop;
    return query insert into public.licences (licence_key, customer_name, customer_email, notes, created_by)
      values (k, left(coalesce(_customer_name,''),120), left(coalesce(_customer_email,''),160), left(coalesce(_notes,''),500), auth.uid()) returning *;
  end loop;
end $$;
revoke all on function public.admin_generate_licences(integer, text, text, text) from public, anon;
grant execute on function public.admin_generate_licences(integer, text, text, text) to authenticated;

-- Main App: activate a key for the signed-in account on this phone
create or replace function public.activate_licence(_key text, _device text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); l public.licences; k text := upper(regexp_replace(coalesce(_key,''), '\s', '', 'g'));
begin
  if uid is null then return jsonb_build_object('ok', false, 'code', 'AUTH', 'message', 'Sign in to activate your licence.'); end if;
  if _device is null or length(_device) < 4 or length(_device) > 128 then return jsonb_build_object('ok', false, 'code', 'DEVICE_ID', 'message', 'This phone has no valid device ID.'); end if;
  if k !~ '^TMK(-[2-9A-HJKMNP-Z]{5}){4}$' then return jsonb_build_object('ok', false, 'code', 'FORMAT', 'message', 'That is not a valid ToneMaster licence key. It starts with TMK-.'); end if;
  select * into l from public.licences where licence_key = k for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'NOT_FOUND', 'message', 'This licence key does not exist. Check it and try again.'); end if;
  if l.status = 'revoked' then return jsonb_build_object('ok', false, 'code', 'REVOKED', 'message', 'This licence key has been revoked. Contact MG:SOUNDS.'); end if;
  if l.user_id is not null and l.user_id <> uid then return jsonb_build_object('ok', false, 'code', 'IN_USE', 'message', 'This licence key is already used by another account.'); end if;
  if l.device_id is not null and l.device_id <> _device then return jsonb_build_object('ok', false, 'code', 'DEVICE', 'message', 'This licence is already active on another phone. Contact MG:SOUNDS to move it to this phone.'); end if;
  update public.licences set user_id = uid, device_id = _device, status = 'active', activated_at = coalesce(activated_at, now()), last_validated_at = now() where id = l.id returning * into l;
  return jsonb_build_object('ok', true, 'id', l.id, 'key', l.licence_key, 'activated_at', l.activated_at, 'customer', l.customer_name);
end $$;
revoke all on function public.activate_licence(text, text) from public, anon;
grant execute on function public.activate_licence(text, text) to authenticated;

-- Main App: re-check the licence for this account + phone on every online start
create or replace function public.check_licence(_device text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); l public.licences;
begin
  if uid is null then return jsonb_build_object('ok', false, 'code', 'AUTH', 'message', 'Sign in again to check your licence.'); end if;
  select * into l from public.licences where user_id = uid and device_id = _device order by activated_at desc nulls last limit 1;
  if not found then return jsonb_build_object('ok', false, 'code', 'NONE', 'message', 'No licence is active for this account on this phone.'); end if;
  if l.status = 'revoked' then return jsonb_build_object('ok', false, 'code', 'REVOKED', 'message', 'This licence has been revoked. Contact MG:SOUNDS.'); end if;
  update public.licences set last_validated_at = now() where id = l.id;
  return jsonb_build_object('ok', true, 'id', l.id, 'key', l.licence_key, 'activated_at', l.activated_at, 'customer', l.customer_name);
end $$;
revoke all on function public.check_licence(text) from public, anon;
grant execute on function public.check_licence(text) to authenticated;